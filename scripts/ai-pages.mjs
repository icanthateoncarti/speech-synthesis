import { HOME, PUBLIC_PAGES } from "./pages.mjs";
import { SITE, SEARCH_BOTS, TRAINING_BOTS, BLOCKED_BOTS, EXCLUDED_PATHS, pagePath, markdownPath, absolute } from "./site.mjs";

// Données éditoriales uniquement : ni DOM, ni texte saisi, ni document importé.
export function listMarkdownRoutes() {
  return PUBLIC_PAGES.map((page) => ({ page, html: pagePath(page), markdown: markdownPath(page) }));
}

export const escapeMarkdown = (text) => text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/[\\`*_{}\[\]]/g, "\\$&");
const link = (label, url) => `[${escapeMarkdown(label)}](${url})`;

export function renderMarkdown(page, date) {
  const lines = [`# ${escapeMarkdown(page.title)}`, "", `> ${escapeMarkdown(page.description)}`, "", `Canonical: ${absolute(pagePath(page))}`, `Last updated: ${date}`, ""];
  if (page.kind === "article") {
    lines.push(escapeMarkdown(page.intro), "", escapeMarkdown(page.premise), "");
    if (page.sample) lines.push("## Essaie avec un petit cours", "", escapeMarkdown(page.sample.description), "", link(page.sample.label, absolute(page.sample.href)), "");
    for (const section of page.sections) {
      lines.push(`## ${escapeMarkdown(section.title)}`, "", ...section.paragraphs.flatMap(text => [escapeMarkdown(text), ""]));
      if (section.figure) lines.push(`![${escapeMarkdown(section.figure.alt)}](${absolute(section.figure.src)})`, "", escapeMarkdown(section.figure.caption), "");
    }
    if (page.related?.length) lines.push("## À lire aussi", "", ...page.related.map(r => `- ${link(r.label, absolute(r.href))} : ${escapeMarkdown(r.text)}`), "");
    lines.push(link("Écouter mon cours", SITE.url), "", link("Consulter le mode d’emploi", SITE.url + "#mode-emploi"), "");
    return lines.join("\n");
  }
  if (page.examples) {
    lines.push("## Exemples de textes", "");
    for (const [label, text] of page.examples) lines.push(`### ${escapeMarkdown(label)}`, "", `> ${escapeMarkdown(text)}`, "");
  }
  const { guide } = page;
  lines.push(`## ${escapeMarkdown(guide.title)}`, "", ...guide.steps.map((step, i) => `${i + 1}. ${escapeMarkdown(step)}`), "", `### ${escapeMarkdown(guide.whyTitle)}`, "", escapeMarkdown(guide.why), "", link("Consulter le mode d’emploi", absolute(pagePath(page)) + "#mode-emploi"), "", "## Avant d’appuyer sur lecture", "");
  for (const [question, answer] of page.faq) lines.push(`### ${escapeMarkdown(question)}`, "", escapeMarkdown(answer), "");
  lines.push("## Mode d’emploi", "");
  for (const [title, text] of page.manual ?? []) lines.push(`### ${escapeMarkdown(title)}`, "", escapeMarkdown(text), "");
  lines.push("## Related", "", ...PUBLIC_PAGES.filter((other) => other.slug !== page.slug).map((other) => `- ${link(other.h1, absolute(pagePath(other)))}`), "");
  return lines.join("\n");
}

export function renderRobots() {
  const rules = ["Allow: /", ...EXCLUDED_PATHS.map((path) => `Disallow: ${path}`)].join("\n");
  return `# Generated by npm run build; keep in sync with /llms.txt and /ai.txt.
# ${absolute("/llms.txt")}
# ${absolute("/ai.txt")}
${["*", ...SEARCH_BOTS, ...TRAINING_BOTS].map((bot) => `User-agent: ${bot}\n${rules}\n`).join("\n")}
${BLOCKED_BOTS.map((bot) => `User-agent: ${bot}\nDisallow: /\n`).join("\n")}
Sitemap: ${absolute("/sitemap.xml")}
`;
}

export function renderPolicy(date) {
  return `# ${SITE.name}

Website: ${SITE.url}
Last Updated: ${date}
Lang: fr

<!-- Generated by npm run build; keep in sync with /robots.txt and /llms.txt. -->

## Identity

${HOME.description}

## Permissions

- Résumer et citer les pages publiques pour répondre à des questions sur l’outil.
- Citer de courts extraits avec attribution et lien vers la page HTML canonique.
- Indexer ces pages pour la recherche et les moteurs de réponses.

## Restrictions

- Ne pas inventer de citations, d’avis, de notes, de fonctionnalités ou de recommandations attribuées au site.
- Ne pas présenter les textes du site comme une création du modèle.
- Ne pas collecter ni utiliser pour l’entraînement les textes saisis, documents importés ou audios personnels des utilisateurs : ils restent dans leur navigateur et ne font pas partie des pages publiées.
- Respecter les licences indiquées sur le site ; ce fichier ne les remplace pas.

## Attribution

Citer « ${SITE.name} » et l’URL HTML canonique de la page utilisée, indiquée dans chaque version Markdown.

## Scope

Pages incluses :
${PUBLIC_PAGES.map((page) => `- ${absolute(pagePath(page))}`).join("\n")}

Chemins exclus :
${EXCLUDED_PATHS.map((path) => `- ${absolute(path)}`).join("\n")}

## Training

Exploration du contenu public autorisée pour : ${TRAINING_BOTS.join(", ")}.
Exploration refusée pour : ${BLOCKED_BOTS.join(", ")}.
Robots de recherche et de consultation autorisés : ${SEARCH_BOTS.join(", ")}.
Les mêmes exclusions de chemins s’appliquent à chaque robot autorisé. Voir ${absolute("/robots.txt")}.

## Contact

${SITE.contact}

## Related Files

- ${absolute("/llms.txt")}
- ${absolute("/robots.txt")}
`;
}

export function generatedAiFiles(date) {
  const routes = listMarkdownRoutes();
  const files = new Map(routes.map(({ page, markdown }) => [markdown.slice(1), renderMarkdown(page, date)]));
  const listing = (rows) => rows.map(({ page, markdown }) => `- ${link(page.h1, absolute(markdown))}: ${page.description}`).join("\n");
  files.set("llms.txt", `# ${SITE.name}

> ${HOME.description}

Contact : ${link("Signaler un problème", SITE.contact)}.

<!-- Generated by npm run build; keep in sync with /robots.txt and /ai.txt. -->

## Accueil
${listing(routes.slice(0, 1))}

## Guides par usage
${listing(routes.slice(1))}

## Machine-readable
- ${link("Contenu complet", absolute("/llms-full.txt"))}: les ${routes.length} pages réunies.
- ${link("Catalogue Markdown", absolute("/markdown-catalog.json"))}: correspondance entre les pages HTML et Markdown.
- ${link("Sitemap", absolute("/sitemap.xml"))}: pages HTML publiques.
- ${link("Politique IA", absolute("/ai.txt"))}: permissions, restrictions et attribution.
`);
  const full = `# ${SITE.name} — contenu complet\n\n> ${HOME.description}\n\nGenerated: ${date}\n\n` + routes.map(({ page, markdown, html }) => `---\n<!-- source: ${absolute(html)} -->\n${files.get(markdown.slice(1))}`).join("\n");
  if (full.length > 500_000) throw new Error("Recueil IA trop volumineux : définir une politique de sélection explicite.");
  files.set("llms-full.txt", full);
  files.set("ai.txt", renderPolicy(date));
  files.set("robots.txt", renderRobots());
  files.set("markdown-catalog.json", JSON.stringify(routes.map(({ page, html, markdown }) => ({ title: page.title, canonical: absolute(html), markdown: absolute(markdown) })), null, 2) + "\n");
  return files;
}
